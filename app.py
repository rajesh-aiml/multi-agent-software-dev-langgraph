
import os
import re
import operator
import subprocess
import sys
import tempfile
from typing import Annotated, List, TypedDict
from pydantic import BaseModel, Field
from langchain_google_genai import ChatGoogleGenerativeAI
from langgraph.graph import StateGraph, END
from langgraph.checkpoint.memory import MemorySaver

MAX_TRIES = 3
USE_DOCKER = False
USE_HUMAN_APPROVAL = False

os.environ["GOOGLE_API_KEY"]="google_api_key_here"

#here to get api key,please go to google AI studio,there select api key,and then please select generate api key,and copy that api key and paste it in
# between "",

llm = ChatGoogleGenerativeAI(model="gemini-2.5-flash", temperature=0.1)


class State(TypedDict):
    task: str
    plan: str
    tests: str
    code: str
    errors: str
    test_results: str
    review: str
    approved: bool
    iterations: int
    report: str
    history: Annotated[List[str], operator.add]



class Review(BaseModel):
  
    approved: bool = Field( description="True if code is correct, clean and safe" )
    feedback: str = Field( description="What must be fixed. Empty if approved.")

reviewer_llm = llm.with_structured_output(Review)



# sending prompt request to llm

def ask(prompt: str) -> str:
    content = llm.invoke(prompt).content

    if isinstance(content, list):
        content = "".join(p if isinstance(p, str) else p.get("text", "") for p in content )

    return content



# Getting only python script from LLM, Instead of Getting all text that is generated by llm
def get_code(text: str) -> str:

    match = re.search( r"```python\s*(.*?)```", text,re.S)
    return match.group(1).strip() if match else text.strip()



# NODES (AGENTS)

# AGENT 1: PLANNER
def planner_node(state: State):

    plan = ask(f""" You are a software architect.

      Task: {state['task']}
      Write a short plan (maximum 5 lines).Include exact function names and signatures.""")

    return { "plan": plan, "history": ["Planner completed the plan."] }



# AGENT 2: TEST WRITER 
def test_writer_node(state: State):

    text = ask(f"""

You are a QA engineer.

Task: {state['task']}
Plan: {state['plan']}

The code will be saved in solution.py.
Start your test file with: from solution import *

Write 3 to 5 tests using plain assert statements.
Include edge cases.

Do NOT implement the function.
Return ONLY a ```python block.

""")

    return { "tests": get_code(text),"history": ["Test Writer generated test cases."]}


# AGENT 3: CODER 
def coder_node(state: State):
    problems = (state["errors"] + "\n" + state["review"]).strip()

    if problems:

        prompt = f"""
        You are an expert Python developer.

        Task: {state['task']}
        Plan: {state['plan']}

        Previous code:```python{state['code'] }```

        Problems found:
        {problems}

        Fix the code.
        Return the FULL corrected code in a ```python block.
        """

    else:
        prompt = f"""
        You are an expert Python developer.

        Task: {state['task']}
        Plan: {state['plan']}

        Write the solution.
        Do NOT include tests.
        Use the exact function names from the plan.
        Return ONLY a ```python block.
        """

    code = get_code(ask(prompt))

    return {

        "code": code,         
        "errors": "", 
        "review": "", 
        "iterations": state["iterations"] + 1,
        "history": [f"Coder generated code. Attempt {state['iterations'] + 1}."]
    }


# AGENT 4: TESTER 
def tester_node(state: State):

    with tempfile.TemporaryDirectory() as folder:
    
        with open( os.path.join(folder, "solution.py"), "w",encoding="utf-8" ) as f:
            f.write(state["code"])
        
        with open( os.path.join(folder, "test_solution.py"), "w",encoding="utf-8") as f:
            f.write(state["tests"])
        
        if USE_DOCKER:
         
            cmd = [
                "docker", "run", "--rm", 
                "--network", "none",     
                "-v", f"{folder}:/app",  
                "-w", "/app",            
                "python:3.12-slim",      
                "python", "test_solution.py" 
            ]

        else:

            cmd = [ sys.executable,"test_solution.py" ]
            

        try:
        
            result = subprocess.run(
                cmd,
                cwd=folder,
                capture_output=True,
                text=True,
                timeout=60

                )

        except Exception as e:
            return { "test_results": "FAILED",
                    "errors": str(e),
                    "history": ["Tester execution failed."]

                    }

    if result.returncode == 0:

        return {

            "test_results": "PASSED",
            "errors": "",
            "history": ["Tester: All tests passed."]
        }

    return {
        "test_results": "FAILED",
        "errors": result.stderr + "\n" + result.stdout,
        "history": ["Tester: Tests failed."]
    }


# AGENT 5: REVIEWER 
def reviewer_node(state: State):

    review = reviewer_llm.invoke(f"""
    You are a strict senior code reviewer.

    Task: {state['task']}

    Code:
      ```python
        {state['code']}
      ```

Check:
1. Does it solve the task correctly?
2. Is the code clean?
3. Is it safe?
4. No file deletion, network calls or dangerous commands.

Return structured approval and feedback.
""")

    return {
        "approved": review.approved,
        "review": review.feedback,
        "history": [
            "Reviewer approved the code."
            if review.approved
            else "Reviewer rejected the code: " + review.feedback
        ]
    }


# AGENT 6: FINAL REPORT 
def report_node(state: State):

    if state["test_results"] == "PASSED" and state["approved"]:
        status = "SUCCESS"

    elif state["test_results"] == "PASSED":
        status = "TESTS PASSED, BUT REVIEWER HAS CONCERNS"

    else:
        status = "FAILED"

    report = f"""
STATUS       : {status}
ATTEMPTS     : {state['iterations']}
TEST RESULTS : {state['test_results']}
LAST ERROR   : {state['errors'] or 'none'}
REVIEWER     : {state['review'] or 'approved'}

EXECUTION HISTORY:
{chr(10).join(state['history'])}

FINAL CODE:
{state['code']}
"""

    return {
        "report": report,
        "history": ["Final report generated."]
    }



#7 ROUTERS

def after_tester(state: State):

    if state["test_results"] == "PASSED":
        return "review" 

    if state["iterations"] >= MAX_TRIES:
        return "report" 

    return "retry" 

def after_reviewer(state: State):

    if state["approved"]: 
        return "report"

    if state["iterations"] >= MAX_TRIES:  
        return "report"

    return "retry" 


#8 BUILD GRAPH

workflow = StateGraph(State)

workflow.add_node("planner", planner_node)
workflow.add_node("test_writer", test_writer_node)
workflow.add_node("coder", coder_node)
workflow.add_node("tester", tester_node)
workflow.add_node("reviewer", reviewer_node)
workflow.add_node("report", report_node)

workflow.set_entry_point("planner")

workflow.add_edge("planner", "test_writer")
workflow.add_edge("test_writer", "coder")
workflow.add_edge("coder", "tester")

workflow.add_conditional_edges("tester",after_tester,

      {
          "review": "reviewer",
          "retry": "coder",
          "report": "report"
      }
)

workflow.add_conditional_edges( "reviewer", after_reviewer,
    {
        "report": "report",
        "retry": "coder"
    }
)

workflow.add_edge("report", END)

memory = MemorySaver()

app = workflow.compile(
    checkpointer=memory,
    interrupt_before=["coder"] if USE_HUMAN_APPROVAL else []
    
)


#9 RUN WITH STREAMING


if __name__ == "__main__":

    config = { "configurable": { "thread_id": "1"} }

    initial_input = {

        "task": "Write a Python function chunk_text to split text into chunks of a given size",
        "plan": "",
        "tests": "",
        "code": "",
        "errors": "",
        "test_results": "",
        "review": "",
        "approved": False,
        "iterations": 0,
        "report": "",
        "history": []
    }

    print("\n--- MULTI-AGENT SOFTWARE DEVELOPMENT SYSTEM ---\n")

    events = app.stream(initial_input, config)
    while True:

        for event in events:
            for node, output in event.items():
                print(f"\n--- {node.upper()} ---")
                print(output)

        
        snapshot = app.get_state(config)

        if not snapshot.next:
            break

        if USE_HUMAN_APPROVAL:

            input("\nGraph paused before Coder. Review state and press Enter to resume...")

            events = app.stream(None, config)

        else:
            break

    final_state = app.get_state(config).values

    if final_state.get("report"):
       
        print(final_state["report"])
